const { withAndroidManifest, withDangerousMod, createRunOncePlugin } = require("expo/config-plugins");
const path = require("node:path");
const fs = require("node:fs");

/**
 * ══════════════════════════════════════════════════════════════════════════════════════════
 *  THE MAIL DOES NOT RIDE A BACKUP — this app's OWN rules, not a dependency's
 * ══════════════════════════════════════════════════════════════════════════════════════════
 *
 * ── THE POSTURE, AND THE HOLE UNDER IT ────────────────────────────────────────────────────
 *
 * `src/state/servers-native.ts` states the credential posture and pins
 * `WHEN_UNLOCKED_THIS_DEVICE_ONLY` to deliver it: "the refresh tokens never ride a cloud or OS
 * backup onto another device". The MAIL those tokens protect had no equivalent. On Android the
 * generated manifest carries `allowBackup="true"`, and the only thing keeping the SQLite
 * mirrors — subjects, senders, every hydrated body — out of the backup was a file this
 * repository does not own: `expo-secure-store`'s own `secure_store_backup_rules.xml` and
 * `secure_store_data_extraction_rules.xml`, which declare
 *
 *     <include domain="sharedpref" path="."/>
 *
 * and nothing else. An include-only ruleset narrows `allowBackup` to sharedprefs, so the
 * `databases` directory falls outside it — protection by accident. A dependency bump that
 * rewrote those two files as exclude-only would silently start backing up the mailbox, and
 * nothing in this tree would fail.
 *
 * So this app declares the exclusion ITSELF. The property then belongs to code we own and can
 * assert on, which is the difference between "Android is fine" and "Android is fine as long as
 * a transitive dependency's XML does not change".
 *
 * ── WHY THE RULES KEEP THE SHAREDPREF INCLUDE ─────────────────────────────────────────────
 *
 * Replacing an include-only ruleset with an exclude-only one would WIDEN the backup to
 * everything not named — the opposite of the intent. So the narrow include is preserved
 * verbatim, `SecureStore` stays excluded (dropping it would put the refresh tokens INTO the
 * backup, which is the one thing the posture is about), and the explicit `database`, `file` and
 * `external` excludes are added on top. Under Android's rules those three are already implied by
 * the include-only shape; they are stated anyway, because a rule that is only true by implication
 * is a rule that stops being true when somebody adds an `<include>`.
 *
 * ── ORDER MATTERS, AND IT IS WHY THIS PLUGIN IS LAST IN `app.json` ────────────────────────
 *
 * `expo-secure-store`'s plugin sets `android:fullBackupContent` and `android:dataExtractionRules`
 * on `<application>`. Whichever plugin runs last wins the attribute, so this one must run after
 * it — hence its position in the `plugins` array. It FAILS LOUD rather than skipping if the
 * manifest has no `<application>` element, because a plugin that quietly applied nothing here
 * would leave every check green over a mailbox in somebody's Google backup.
 *
 * ── iOS IS NOT FIXED HERE, AND THAT IS SAID RATHER THAN IMPLIED ───────────────────────────
 *
 * expo-sqlite's iOS default directory is `documentDirectory/SQLite`, which the platform's own
 * cloud and computer backups include unless the file carries `NSURLIsExcludedFromBackupKey`
 * (the backup service's brand name is not spelled here — the privacy census bans real brand
 * strings in this app's source, `test/privacy.test.ts`). Setting
 * that attribute needs native code this plugin does not write, so the iOS half remains open and
 * is tracked as such; the app's own copy says so rather than claiming a parity it does not have.
 */

/** The generated resource names. Exported so the test compares values, never two copies. */
const BACKUP_RULES_RES = "ohmail_backup_rules";
const DATA_EXTRACTION_RULES_RES = "ohmail_data_extraction_rules";

/** Android 11 and lower — `android:fullBackupContent`. */
const BACKUP_RULES_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/mobile/plugins/backup-exclusions.js — do not edit in android/. -->
<full-backup-content>
  <include domain="sharedpref" path="."/>
  <exclude domain="sharedpref" path="SecureStore"/>
  <exclude domain="database" path="."/>
  <exclude domain="file" path="."/>
  <exclude domain="external" path="."/>
</full-backup-content>
`;

/** Android 12 and higher — `android:dataExtractionRules`, cloud backup AND device transfer. */
const DATA_EXTRACTION_RULES_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/mobile/plugins/backup-exclusions.js — do not edit in android/. -->
<data-extraction-rules>
  <cloud-backup>
    <include domain="sharedpref" path="."/>
    <exclude domain="sharedpref" path="SecureStore"/>
    <exclude domain="database" path="."/>
    <exclude domain="file" path="."/>
    <exclude domain="external" path="."/>
  </cloud-backup>
  <device-transfer>
    <include domain="sharedpref" path="."/>
    <exclude domain="sharedpref" path="SecureStore"/>
    <exclude domain="database" path="."/>
    <exclude domain="file" path="."/>
    <exclude domain="external" path="."/>
  </device-transfer>
</data-extraction-rules>
`;

/**
 * Point `<application>` at this app's own rules. A pure function over the parsed manifest so the
 * test can drive it without a generated project.
 */
function pointManifestAtOurRules(manifest) {
  const application = manifest?.manifest?.application?.[0];
  if (!application) {
    throw new Error(
      "ohmail backup-exclusions: the generated AndroidManifest has no <application> element, so " +
        "the mirror's backup exclusion was not applied. Refusing rather than shipping a build " +
        "whose mail can ride a cloud backup.",
    );
  }
  application.$ = application.$ ?? {};
  application.$["android:fullBackupContent"] = `@xml/${BACKUP_RULES_RES}`;
  application.$["android:dataExtractionRules"] = `@xml/${DATA_EXTRACTION_RULES_RES}`;
  return manifest;
}

function withBackupExclusions(config) {
  config = withDangerousMod(config, [
    "android",
    (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, "app", "src", "main", "res", "xml");
      fs.mkdirSync(dir, { recursive: true });
      // Rewritten on EVERY prebuild, not written once: `expo prebuild` runs over an existing
      // android/ tree by default, and a "skip if present" plugin is how stale rules ship while
      // every grep for the marker stays green (the lesson `release-minification.js` paid for).
      fs.writeFileSync(path.join(dir, `${BACKUP_RULES_RES}.xml`), BACKUP_RULES_XML, "utf8");
      fs.writeFileSync(path.join(dir, `${DATA_EXTRACTION_RULES_RES}.xml`), DATA_EXTRACTION_RULES_XML, "utf8");
      return cfg;
    },
  ]);
  return withAndroidManifest(config, (cfg) => {
    cfg.modResults = pointManifestAtOurRules(cfg.modResults);
    return cfg;
  });
}

module.exports = createRunOncePlugin(withBackupExclusions, "ohmail-backup-exclusions", "1.0.0");
module.exports.BACKUP_RULES_RES = BACKUP_RULES_RES;
module.exports.DATA_EXTRACTION_RULES_RES = DATA_EXTRACTION_RULES_RES;
module.exports.BACKUP_RULES_XML = BACKUP_RULES_XML;
module.exports.DATA_EXTRACTION_RULES_XML = DATA_EXTRACTION_RULES_XML;
module.exports.pointManifestAtOurRules = pointManifestAtOurRules;
