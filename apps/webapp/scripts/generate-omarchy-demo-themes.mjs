/* Generates app/(marketing)/components/omarchy-demo-themes.ts — the landing theme
   explorer's data: every Omarchy fixture theme mapped through THE palette law
   (packages/tokens/omarchy/mapping.js) into ohmail token values, plus the three raw
   palette colors the picker's swatches show.

   The landing demo's ohmarchy face flips through the real Omarchy themes, driven by the
   fixture palettes shipped with the demo — the same mapping the app itself uses, reused
   rather than rebuilt. The fixtures are the ground truth captured off a real Omarchy
   4.0.2 install (their provenance is inside each file); nothing is fetched at build time.

   The output is DETERMINISTIC and committed: test/landing-faces.test.ts re-runs this
   generation in-process and fails if the committed module differs, so a hand edit cannot
   survive a test run, and a mapping.js change that shifts any value shows up as a diff
   here rather than as silent drift between the demo and the law. Regenerate with:

     node apps/webapp/scripts/generate-omarchy-demo-themes.mjs

   (run from the repository root)
*/
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (rel) => fileURLToPath(new URL(rel, import.meta.url));
const FIXTURES = "../../../packages/tokens/omarchy/fixtures";

/** Build the module text from the fixtures — exported so the pin test can compare
 *  without touching the filesystem (writing stays the CLI entry's job). */
export async function generateModuleText() {
  // UMD side effect: registers globalThis.OHMARCHY_MAP (same move as map.ts / the gallery).
  await import(here("../../../packages/tokens/omarchy/mapping.js"));
  const MAP = globalThis.OHMARCHY_MAP;
  const index = JSON.parse(readFileSync(here(`${FIXTURES}/index.json`), "utf8"));

  const themes = index.themes.map(({ slug }) => {
    const fixture = JSON.parse(readFileSync(here(`${FIXTURES}/${slug}.json`), "utf8"));
    const mapped = MAP.mapTheme(fixture);
    return {
      slug: fixture.slug,
      name: fixture.name,
      mode: fixture.mode,
      /* the picker swatch: the palette's own ground, ink and accent — raw, because the
         swatch depicts the THEME, while `tokens` is what the demo actually wears */
      swatch: {
        bg: fixture.colors.background,
        fg: fixture.colors.foreground,
        accent: fixture.colors.accent,
      },
      tokens: mapped.tokens,
    };
  });

  return `/* GENERATED by apps/webapp/scripts/generate-omarchy-demo-themes.mjs — never
   hand-edited (a test re-runs the generation and pins this file to it). Every token
   value comes from packages/tokens/omarchy/mapping.js over the committed fixture
   palettes: the demo explorer wears exactly what the mapping derives — the same values
   the desktop derives when it follows a live Omarchy theme. */

export interface OmarchyDemoTheme {
  slug: string;
  name: string;
  mode: "light" | "dark";
  swatch: { bg: string; fg: string; accent: string };
  tokens: Record<string, string>;
}

export const OMARCHY_DEMO_THEMES: readonly OmarchyDemoTheme[] = ${JSON.stringify(themes, null, 2)};
`;
}

const invokedDirectly =
  process.argv[1] && fileURLToPath(new URL(import.meta.url)) === fileURLToPath(new URL(`file://${process.argv[1]}`));

if (invokedDirectly) {
  const out = here("../app/(marketing)/components/omarchy-demo-themes.ts");
  writeFileSync(out, await generateModuleText());
  console.log(`wrote ${out}`);
}
