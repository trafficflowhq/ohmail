/**
 * Every letter the look before landing and its recheck tried on the found-events rules, each with the
 * reading a person calls right: the module's memory. A rule that reads one of them differently turns
 * its row red. Read as the corpus's letters are: sent on Tuesday 10 November 2026 at 09:00 in Zurich,
 * read an hour later, by a person in Europe/Zurich.
 *
 * A reading is written as `readingOf` in found-tried.test.ts writes it: each finding as its level, its
 * key and, when the words gave one, its end ("dated 2026-11-21T18:00-20:00"); each word for what was
 * not offered ("not two_dates"); "asked 2" for the sentences a model may be asked about; "nothing"
 * for none of these.
 *
 * `lost` marks a row whose right reading is the safe one: the letter names an event the rules do not
 * read, and they offer nothing, or the whole day, rather than guess. The row pins that.
 * `owed` marks a row the rules read wrongly today, with the finding that owes it; the row asserts the
 * right reading and is expected to fail until that finding is fixed. "later: cancel" rows wait for the
 * round that adds the cancelled forms; "D, left" rows are hours words not yet known; "seen" rows were
 * seen in passing and belong to no finding yet.
 */
