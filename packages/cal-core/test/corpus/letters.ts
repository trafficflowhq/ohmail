/**
 * Invented letters for the found-events rules, in English and German. Every person, place and
 * address is made up; an address ends in `.example`. Each letter says what a reading of it must
 * give: one finding, or the words for why nothing is offered.
 *
 * Unless a letter says otherwise it was sent on Tuesday 10 November 2026 at 09:00 in Zurich and is
 * read an hour later, by a person in Europe/Zurich.
 */
import type { FoundLanguage, FoundLevel, FoundKind, NotOfferedWord } from "@ohmail/cal-core/found/types";

export interface Letter {
  readonly name: string;
  readonly subject: string;
  readonly body: string;
  readonly language: FoundLanguage | null;
  /** `undefined` only where a letter tests a missing place. */
  readonly place?: string;
  readonly sentAt?: string;
  readonly now?: string;
  readonly zone?: string;
  readonly expect: Expected;
}

export interface Expected {
  /** The finding's start as written, or `null` for none. */
  readonly key: string | null;
  readonly level?: FoundLevel;
  readonly kind?: FoundKind;
  /** The end's clock reading, `2026-11-21T20:30`, or `null` for a whole day. */
  readonly end?: string | null;
  readonly endGiven?: boolean;
  /** The words of the finding, as they stand in the letter. */
  readonly words?: readonly string[];
  /** Words for what was not offered; every one must be in the reading, in this order. */
  readonly not?: readonly NotOfferedWord[];
  /** Sentences a model may be asked about. */
  readonly asks?: readonly string[];
}

