/* Writes src/design/ from source/tokens.json and source/motion.json:

     tokens.css   one rule per source block, selectors on the root's data attributes
     motion.css   the motion tokens, and what they become under reduced motion
     tokens.ts    the same values resolved per context, typed
     tokens.json  that data for readers that are not TypeScript

   The output is deterministic and committed. test/design-generated-identity.test.ts runs this
   in-process and fails when a committed file differs, so a hand edit of an output does not
   survive a test run: change the source and run `node packages/tokens/scripts/generate-design.mjs`.

   One thing here is not in the source: a block that answers to data-scheme="dark" is written a
   second time for a document that stamps no scheme and whose system asks for dark. */
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  BASE_ACCENT, FACES, SCHEMES, SourceError, blocksOf, cascade, motionOf, readSource, resolveAll, selectorOf,
} from "./design-lib.mjs";

const HEADER = (from) =>
  `/* GENERATED by packages/tokens/scripts/generate-design.mjs from ${from}.\n   Never edited by hand: change the source and run the script. */\n`;

const body = (decls) => Object.entries(decls).map(([name, value]) => `  --${name}: ${value};\n`).join("");
const rule = (selector, decls) => `${selector}{\n${body(decls)}}\n`;

/** tokens.css: every block in the sheet's order, a dark block followed by its system-scheme twin. */
function tokensCss(blocks) {
  let out = HEADER("source/tokens.json");
  for (const block of blocks) {
    if (Object.keys(block.decls).length === 0) continue;
    out += `\n${rule(selectorOf(block.when), block.decls)}`;
    if (block.when.scheme !== "dark") continue;
    const twin = rule(selectorOf(block.when, { systemScheme: true }), block.decls);
    out += `@media (prefers-color-scheme: dark){\n${twin}}\n`;
  }
  return out;
}

/** motion.css: slick on the root; the reduced set by attribute and by the system's own setting. */
function motionCss(motion) {
  const slick = { ...motion.time, ...motion.slick, ...motion.calendar.slick };
  const reduced = { ...motion.reduced, ...motion.calendar.reduced };
  return (
    `${HEADER("source/motion.json")}\n${rule(":root", slick)}\n` +
    `${rule(':root[data-rm="1"],\n[data-rm="1"]', reduced)}\n` +
    `@media (prefers-reduced-motion: reduce){\n${rule(":root", reduced)}}\n`
  );
}

/* The situations the resolved data answers for. `phone` and `fold` are touch devices. */
const SITUATIONS = {
  light: {},
  dark: { scheme: "dark" },
  touch: { touch: "1" },
  phone: { touch: "1", device: "phone" },
  fold: { touch: "1", device: "fold" },
  foldWords: { touch: "1", device: "fold", icons: "0" },
};
const CALENDAR_SITUATIONS = {
  light: {},
  dark: { scheme: "dark" },
  touch: { touch: "1" },
  phone: { touch: "1", device: "phone" },
  fold: { touch: "1", device: "fold" },
  land: { touch: "1", device: "fold", pose: "land", icons: "1" },
  alone: { cal: "alone" },
};

const pick = (map, names) => Object.fromEntries(names.filter((n) => n in map).map((n) => [n, map[n]]));
const round1 = (n) => Math.round(n * 10) / 10;

/** The values every context resolves to, in the source's shape. */
function resolved(tokens, blocks) {
  const names = (path) => Object.keys(blocks.find((b) => b.path === path).decls);
  const mailNames = names("faces.paper.light");
  const calendarNames = names("calendar.paper.light");
  const productNames = names("product.cal");
  const accentNames = [...new Set(blocks.filter((b) => b.path.startsWith("accents.")).flatMap((b) => Object.keys(b.decls)))];
  const accentCtx = (name) => (tokens.accents[name] === BASE_ACCENT ? {} : { accent: name });
  /* No data-sqtone here: which tone a read square takes is `readSquare`, stamped by the frame. */
  const at = (face, situation, accent, more = {}) =>
    resolveAll(cascade(blocks, { face, ...situation, ...accentCtx(accent), ...more }));
  const perFace = (fn) => Object.fromEntries(FACES.map((face) => [face, fn(face)]));
  const perScheme = (fn) => Object.fromEntries(SCHEMES.map((scheme) => [scheme, fn(scheme, SITUATIONS[scheme])]));
  const each = (situations, fn) => Object.fromEntries(Object.entries(situations).map(([k, s]) => [k, fn(s)]));

  const mail = tokens.productAccent.mail;
  const calAccent = (face, scheme) => tokens.calendar.accents[tokens.productAccent.cal][face][scheme].resolvesTo;
  const inCalendar = (face, situation) =>
    at(face, situation, calAccent(face, situation.scheme ?? "light"), { product: "cal" });
  const ring = tokens.calendar.ring;
  const calendarAccent = (entry) => ({
    ...entry,
    hues: Object.fromEntries(ring.map(({ name, hue }) => [name, round1(hue + entry.turn)])),
  });

  return {
    sheet: tokens.sheet,
    productAccent: tokens.productAccent,
    faces: perFace((face) => each(SITUATIONS, (s) => pick(at(face, s, mail), mailNames))),
    accents: Object.fromEntries(
      Object.keys(tokens.accents).map((name) => [
        name,
        perFace((face) => perScheme((_, s) => pick(at(face, s, name), accentNames))),
      ]),
    ),
    readSquare: tokens.readSquare,
    product: { cal: perFace((face) => perScheme((_, s) => pick(inCalendar(face, s), productNames))) },
    avatarHues: tokens.avatarHues,
    tagHues: tokens.tagHues,
    calendar: {
      ...perFace((face) => each(CALENDAR_SITUATIONS, (s) => pick(inCalendar(face, s), calendarNames))),
      ring,
      accents: Object.fromEntries(
        Object.entries(tokens.calendar.accents).map(([name, accent]) => [
          name,
          perFace((face) => perScheme((scheme) => calendarAccent(accent[face][scheme]))),
        ]),
      ),
    },
  };
}

function resolvedMotion(motion) {
  const part = ({ slick, reduced }) => {
    const whole = resolveAll(slick, motion.time);
    return { slick: whole, reduced: { ...whole, ...resolveAll(reduced, motion.time) } };
  };
  return { ...motion.time, ...part(motion), calendar: part(motion.calendar) };
}

const roles = (slick) => Object.keys(slick).filter((n) => n.startsWith("d-") && n !== "d-reduced").map((n) => n.slice(2));

function tokensTs(design, motion) {
  const literal = (value) => JSON.stringify(value, null, 2);
  return `${HEADER("source/tokens.json and source/motion.json")}
/** Every value of the design, resolved for each situation a document can be in. */
export const design = ${literal(design)} as const;

/** The motion tokens; \`reduced\` is the whole set as it stands under reduced motion. */
export const motion = ${literal(motion)} as const;

/** What a duration is for: the \`<role>\` of \`--d-<role>\`. */
export const motionRoles = ${JSON.stringify([...roles(motion.slick), ...roles(motion.calendar.slick)])} as const;
export type MotionRole = (typeof motionRoles)[number];

export type TokenName =
  | keyof typeof design.faces.paper.light
  | keyof typeof design.calendar.paper.light
  | keyof typeof motion.slick
  | keyof typeof motion.calendar.slick
  | "m-time";

/** The custom property of a token, for a style that is not a stylesheet. */
export const v = <N extends TokenName>(name: N) => \`var(--\${name})\` as const;
`;
}

/** Every generated file, by name. Throws SourceError on a source it cannot emit whole. */
export function generate(source = readSource()) {
  const blocks = blocksOf(source.tokens);
  const motion = motionOf(source.motion);
  const design = resolved(source.tokens, blocks);
  const moves = resolvedMotion(motion);
  return {
    "tokens.css": tokensCss(blocks),
    "motion.css": motionCss(motion),
    "tokens.ts": tokensTs(design, moves),
    "tokens.json": `${JSON.stringify({ design, motion: moves }, null, 2)}\n`,
  };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  try {
    const dir = fileURLToPath(new URL("../src/design/", import.meta.url));
    mkdirSync(dir, { recursive: true });
    for (const [name, text] of Object.entries(generate())) writeFileSync(`${dir}${name}`, text);
  } catch (error) {
    if (!(error instanceof SourceError)) throw error;
    process.stderr.write(`generate-design: ${error.message}\n`);
    process.exit(1);
  }
}
