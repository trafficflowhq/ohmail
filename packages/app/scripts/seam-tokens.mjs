#!/usr/bin/env node
/**
 * Keep the frame's tokens under its own root. The host documents also load the older tokens at
 * the document root. Some shared names have different values, including the frame's shadow.
 * Run with --write to regenerate the frame sheet.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const TOKENS = "packages/tokens/src";
export const OLD_SHEETS = [`${TOKENS}/tokens.css`, `${TOKENS}/faces.css`, `${TOKENS}/ohmarchy.css`];
/* The kit's base writes measures of its own on the root that read the shared names: they are the new design's too. */
export const NEW_SHEETS = [`${TOKENS}/design/tokens.css`, "packages/ui/src/base/base.css"];
export const FRAME_SHEET = "packages/app/src/frame/seam.generated.css";

/** The rules of a sheet, each with the media query it stands in, if any. Comments are dropped. */
export function rulesOf(css) {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const rules = [];
  const walk = (body, media) => {
    let at = 0;
    while (at < body.length) {
      const open = body.indexOf("{", at);
      if (open === -1) break;
      /* What follows the last statement before the brace (`@layer oh;` ends one). */
      const before = body.slice(at, open);
      const head = before.slice(before.lastIndexOf(";") + 1).trim();
      let depth = 1;
      let end = open + 1;
      for (; end < body.length && depth > 0; end++) {
        if (body[end] === "{") depth++;
        else if (body[end] === "}") depth--;
      }
      const inner = body.slice(open + 1, end - 1);
      if (head.startsWith("@media")) walk(inner, head);
      else if (head.startsWith("@layer")) walk(inner, media);
      else if (!head.startsWith("@"))
        rules.push({
          media,
          selectors: head.split(",").map((s) => s.trim()),
          declarations: declarationsOf(inner),
        });
      at = end;
    }
  };
  walk(text, null);
  return rules;
}

function declarationsOf(block) {
  return block
    .split(";")
    .map((d) => d.trim())
    .filter(Boolean)
    .map((d) => {
      const colon = d.indexOf(":");
      return { name: d.slice(0, colon).trim(), value: d.slice(colon + 1).trim() };
    });
}

const declared = (rules) =>
  new Set(rules.flatMap((r) => r.declarations.map((d) => d.name)).filter((n) => n.startsWith("--")));

/** The names both designs define, sorted. */
export function sharedNames(oldRules, newRules) {
  const old = declared(oldRules);
  return [...declared(newRules)].filter((name) => old.has(name)).sort();
}

/**
 * The shared names and every name of the same design whose value reads one of them, however deep: a value
 * like `color-mix(…, var(--ink) …)` is resolved where it is declared, on `:root`, so it must be declared
 * again under the seam too, or it carries the other design's meaning down.
 */
export function namesReading(rules, shared) {
  const names = new Set(shared);
  for (let grew = true; grew;) {
    grew = false;
    for (const { name, value } of rules.flatMap((r) => r.declarations)) {
      if (names.has(name) || !name.startsWith("--")) continue;
      if ([...value.matchAll(/var\((--[A-Za-z0-9-]+)/g)].some(([, used]) => names.has(used))) {
        names.add(name);
        grew = true;
      }
    }
  }
  return [...names].sort();
}

/** A rule written on the document's root or a themed ancestor: a custom property a part declares on itself resolves there. */
const onTheRoot = (rule) => rule.selectors.every((s) => s.startsWith(":root") || s.startsWith("[data-"));

function sheet(rules, shared, under, from) {
  const covered = namesReading(rules, shared);
  const out = [
    `/* GENERATED by packages/app/scripts/seam-tokens.mjs from ${from.join(", ")}. Never edited by hand.`,
    `   The names both designs define (${shared.join(", ")}) and those read off them, declared again under ${under}. */`,
    "",
  ];
  for (const rule of rules.filter(onTheRoot)) {
    const kept = rule.declarations.filter((d) => covered.includes(d.name));
    if (!kept.length) continue;
    const selector = rule.selectors.map((s) => `${s} ${under}`).join(",\n");
    const body = kept.map((d) => `  ${d.name}: ${d.value};`).join("\n");
    const block = `${selector} {\n${body}\n}`;
    out.push(rule.media ? `${rule.media} {\n${block.replace(/^/gm, "  ")}\n}` : block, "");
  }
  return out.join("\n");
}

/** The sender and audit sheets read the host's names. Give them the frame's palette when mounted inside it. */
function screeningSheet() {
  const root = ".fr-root";

  return `
/* The hosted screening sheets use the frame palette. Capture its shadow before the sheets map --float to a fill. */
${root} {
  --screening-lift: var(--float);
}

${root} :is(.senderm, .senderm-veil, .sa, .sa-bg) {
  --z-pal: var(--oh-layer-top);
}

${root} :is(.senderm, .sa) {
  --float: var(--sheet);
  --panel: var(--sheet);
  --tint: var(--soft-sheet);
  --accent-soft: var(--sheet-new);
  --accent: var(--hot);
  --accent-hair: var(--hot);
  --accent-ink: var(--hot-ink);
  --on-accent: var(--on-hot);
  --hair-soft: var(--line-soft);
  --r-overlay: var(--r-sheet);
  --r-card: var(--r-row);
  --r-ctl: var(--r-row);
  --lift-0: var(--oh-ring-line);
  --lift-3: var(--screening-lift);
}
`;
}

/** The shared names and the frame sheet, generated from the source tokens. */
export function seamSheets(root = ROOT) {
  const read = (files) => files.flatMap((file) => rulesOf(readFileSync(join(root, file), "utf8")));
  const oldRules = read(OLD_SHEETS);
  const newRules = read(NEW_SHEETS);
  const shared = sharedNames(oldRules, newRules);
  return {
    shared,
    frame: sheet(newRules, shared, ".oh-root", NEW_SHEETS) + screeningSheet(),
  };
}

function main(argv) {
  const sheets = seamSheets();
  const path = join(ROOT, FRAME_SHEET);
  if (argv.includes("--write")) {
    writeFileSync(path, sheets.frame);
    console.log(`seam-tokens: wrote ${FRAME_SHEET} (${sheets.shared.length} shared names)`);
    return 0;
  }
  if (existsSync(path) && readFileSync(path, "utf8") === sheets.frame) return 0;
  console.log(`seam-tokens: ${FRAME_SHEET} is stale; run with --write`);
  return 1;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1])
  process.exitCode = main(process.argv.slice(2));
